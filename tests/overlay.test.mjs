test('base and components rule diff, incl. @media-wrapped rules and leading comments', () => {
  const full = REF_TEXT.replace('  a { color: var(--color-accent);', '  /* links: thicker offset */\n  a { color: var(--color-accent);')
    .replace('text-underline-offset: 0.2em; }', 'text-underline-offset: 0.3em; }')
    .replace('@media (min-width: 640px) { .lead { font-size: 1.25rem; } }', '@media (min-width: 640px) { .lead { font-size: 1.5rem; } }')
    .replace('.chip-ok { background: var(--color-ok-soft); color: var(--color-ok); }', '.chip-ok { background: var(--color-ok-soft); color: var(--color-ok); border-color: transparent; }')
    .replace('  .mono {', '  .tag-new { color: red; }\n  .mono {');
  const { css, report } = build(full);
  assert.deepEqual(report.rules.base, ['a']);
  assert.deepEqual(report.rules.components, ['@media (min-width: 640px) { .lead }', '.chip-ok', '.tag-new']);
  assert.deepEqual(report.newSelectors, ['.tag-new']);
  const base = blockOf(css, '@layer base');
  assert.match(base, / {2}\/\* links: thicker offset \*\/\n {2}a \{\n {4}color: var\(--color-accent\);\n {4}text-decoration-thickness: 1px;\n {4}text-underline-offset: 0\.3em;\n {2}\}/);
  const comp = blockOf(css, '@layer components');
  assert.match(comp, / {2}@media \(min-width: 640px\) \{\n {4}\.lead \{\n {6}font-size: 1\.5rem;\n {4}\}\n {2}\}/);
  assert.match(comp, /\.chip-ok \{\n {4}background: var\(--color-ok-soft\);\n {4}color: var\(--color-ok\);\n {4}border-color: transparent;\n {2}\}/);
  assert.ok(!comp.includes('.chip-warn'));
  assert.ok(!/\n\n\n/.test(css), 'no double blank lines');
  const cmp = compareOverlay(REF_TEXT, css);
  assert.equal(cmp.ok, true);
  assert.deepEqual(cmp.new_selectors, ['.tag-new']);
});

