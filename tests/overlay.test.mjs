test('compareOverlay: findings', () => {
  const r = compareOverlay(
    REF_TEXT,
    `.card { color: red; }
@import "@fontsource-variable/x/wght.css";
@import "tailwindcss";
@import url("https://fonts.googleapis.com/css2?family=X");
@layer base;
@theme { --color-bg: red; }
:root { --color-new: red; --color-bg: #fff; --header-h: 3rem; }
:root[data-theme="dark"] { --color-bg: #000; --color-ink: #eee; }
@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { --color-bg: #111; --color-ink: #eee; } }
@layer components { .btn { @apply px-4; color: theme(--color-ink); margin: 0 !important; } }
@media (prefers-reduced-motion: reduce) { .btn { transition: none !important; } }`,
  );
  assert.equal(r.ok, false);
  assert.deepEqual(r.unknown_tokens, ['--color-new']);
  assert.deepEqual(r.dark_missing, { root: ['--color-ink'], data_theme: ['--color-new'], media: ['--color-new'] });
  assert.deepEqual(r.dark_mismatch, [{ prop: '--color-bg', data_theme: '#000', media: '#111' }]);
  const f = r.forbidden.map((x) => x.text).join('\n');
  for (const want of ['@import "tailwindcss";', '@layer base;', '@theme {', '@apply px-4;', 'color: theme(--color-ink)']) assert.ok(f.includes(want), want);
  assert.equal(r.external_imports.length, 1);
  assert.equal(r.important.length, 1);
  assert.equal(r.imports_after_rules.length, 3);
});

test('overlay.mjs CLI: writes, --json, exit 1 when nothing differs, --allow-empty, exit 2 on a non-full theme', () => {
  const out = tmpFile('', '.css');
  const r = run('overlay.mjs', [REF, join(RUN, 'theme.ai-architect-blog.css'), '--out', out, '--site', 'www', '--slug', 'ai-architect-blog', '--approval', 'approve B', '--json']);
  assert.equal(r.code, 0, r.stderr);
  const j = JSON.parse(r.stdout);
  assert.equal(j.out, out);
  assert.equal(j.empty, false);
  assert.match(r.stderr, /removed/);
  assert.equal(readFileSync(out, 'utf8'), readFileSync(join(RUN, 'site.ai-architect-blog.css'), 'utf8'));

  const same = join(tmpFile('', '.d'), '..', 'same-site.css');
  const e = run('overlay.mjs', [REF, REF, '--out', same]);
  assert.equal(e.code, 1);
  assert.equal(existsSync(same), false);
  const a = run('overlay.mjs', [REF, REF, '--out', same, '--allow-empty']);
  assert.equal(a.code, 0, a.stderr);
  assert.equal(compareOverlay(REF_TEXT, readFileSync(same, 'utf8')).empty, true);

  const notFull = tmpFile(REF_TEXT.replace('@import "tailwindcss";\n@source "../";', ''));
  assert.equal(run('overlay.mjs', [REF, notFull, '--out', out]).code, 2);
  assert.equal(run('overlay.mjs', [REF, 'missing.css', '--out', out]).code, 2);
  assert.equal(run('overlay.mjs', [REF, REF]).code, 2);
  assert.match(run('overlay.mjs', ['--help']).stdout, /--json/);
});
