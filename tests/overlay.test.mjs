/** Text of the rule (or block) starting with `head {` in css, up to its matching brace. */
function blockOf(css, head) {
  const i = css.indexOf(`${head} {`);
  if (i === -1) return null;
  let depth = 0;
  for (let j = css.indexOf('{', i); j < css.length; j++) {
    if (css[j] === '{') depth++;
    else if (css[j] === '}' && --depth === 0) return css.slice(i, j + 1);
  }
  return null;
}

