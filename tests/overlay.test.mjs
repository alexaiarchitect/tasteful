test('a removed shorthand is reset before the longhands that replace it', () => {
  const full = REF_TEXT.replace(
    /background:\n\s*radial-gradient\(60rem[\s\S]*?transparent 70%\);/,
    'background-image: radial-gradient(red 1px, transparent 1.5px);\n    background-size: 14px 14px;',
  );
  const { css, report } = build(full);
  assert.deepEqual(report.removed, [{ selector: '.hero-wash::before', props: ['background'] }]);
  const rule = blockOf(css, '.hero-wash::before');
  const at = (s) => rule.indexOf(s);
  assert.ok(at('background: unset;') !== -1 && at('background: unset;') < at('content: ""') && at('content: ""') < at('background-image:'), rule);
  assert.ok(at('background-size: 14px 14px;') > at('background: unset;'));
});

